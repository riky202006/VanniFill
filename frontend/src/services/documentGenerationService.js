/**
 * Document Generation Service for VaaniFill AI
 * Integration point for generating completed forms overlaying original PDFs/images.
 * Clearly separates full PDF generation from text summary fallback without false claims.
 */

import { API_BASE_URL } from '../constants/api'

export async function generateCompletedDocument({ documentId, fields = [], fieldValues = {}, originalFileName = 'form.pdf' }) {
  // If backend endpoint for PDF rendering exists: POST /api/forms/generate
  const generateUrl = `${API_BASE_URL}/forms/generate`

  try {
    const response = await fetch(generateUrl, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        documentId,
        fieldValues,
      }),
    })

    if (!response.ok) {
      throw new Error(`Generation endpoint returned HTTP ${response.status}`)
    }

    const blob = await response.blob()
    const downloadUrl = URL.createObjectURL(blob)
    return {
      success: true,
      isRealDocument: true,
      downloadUrl,
      fileName: `Completed_${originalFileName}`,
      message: 'Completed document successfully generated by the backend pipeline.',
    }
  } catch (error) {
    // Return honest unconnected status
    return {
      success: false,
      isRealDocument: false,
      downloadUrl: null,
      error: 'Backend document-generation service is not connected yet.',
      message: 'Generating a filled PDF overlaying your original form requires the backend document-generation service, which is not yet deployed. You can download an extracted field summary below.',
    }
  }
}

/**
 * Clean field-summary export (explicitly identified as a data summary, not a filled PDF).
 */
export function downloadFieldsSummary({ originalFileName, formTitle, fields = [], fieldValues = {}, isFixture = false }) {
  const filledFields = fields.filter((f) => {
    const val = fieldValues[f.id] ?? f.userValue ?? f.detectedValue
    return val !== null && val !== undefined && String(val).trim() !== ''
  })
  const emptyFields = fields.length - filledFields.length

  const lines = [
    '====================================================',
    'VAANIFILL AI - EXTRACTED FORM FIELDS SUMMARY',
    '====================================================',
    `Export Timestamp:  ${new Date().toLocaleString()}`,
    `Original Document: ${originalFileName || 'Uploaded Document'}`,
    `Form Title:        ${formTitle || 'Detected Digital Form'}`,
    `Data Mode:         ${isFixture ? 'Demonstration Fixture (Unconnected Service)' : 'Processed Document'}`,
    '',
    'NOTICE TO USER:',
    'This file is a structured summary of the fields identified and values',
    'entered for your form. It is NOT a filled copy of the original PDF.',
    '',
    '----------------------------------------------------',
    'FORM FIELDS & VALUES',
    '----------------------------------------------------',
  ]

  fields.forEach((f, idx) => {
    const rawVal = fieldValues[f.id] ?? f.userValue ?? f.detectedValue
    const valStr = rawVal !== null && rawVal !== undefined && String(rawVal).trim() !== ''
      ? String(rawVal).trim()
      : '(Empty / Not Provided)'
    const sourceTag = f.source === 'found_in_document'
      ? '[Found in Document]'
      : f.source === 'suggested'
      ? '[Suggested by Assistant]'
      : f.source === 'user_entered'
      ? '[Entered by User]'
      : '[Unfilled]'

    lines.push(`${idx + 1}. ${f.label.padEnd(35)}: ${valStr} ${sourceTag}`)
  })

  lines.push('')
  lines.push('----------------------------------------------------')
  lines.push('STATISTICS')
  lines.push('----------------------------------------------------')
  lines.push(`Total Form Fields:     ${fields.length}`)
  lines.push(`Completed Fields:      ${filledFields.length}`)
  lines.push(`Empty Required Fields: ${emptyFields}`)
  lines.push('')
  lines.push('====================================================')
  lines.push('VaaniFill AI — Multilingual Form Automation')
  lines.push('All values remained local to your browser session.')
  lines.push('====================================================')

  const blob = new Blob([lines.join('\n')], { type: 'text/plain;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = `VaaniFill-Extracted-Fields-Summary.txt`
  document.body.appendChild(link)
  link.click()
  document.body.removeChild(link)
  URL.revokeObjectURL(url)
}

export default {
  generateCompletedDocument,
  downloadFieldsSummary,
}
